def check_guess(guess, secret):
    """
    Compare guess to secret and return (outcome, message).

    outcome examples: "Win", "Too High", "Too Low"
    """
    if guess == secret:
        return "Win", "🎉 Correct!"

    # FIX: Agent diagnosed that the original code had swapped messages — "Too High" said "Go HIGHER!" and "Too Low" said "Go LOWER!" — which is why every hint pointed the player away from the secret. Pair-moved from app.py into logic_utils so pytest can target it directly.
    if guess > secret:
        return "Too High", "📉 Go LOWER!"
    return "Too Low", "📈 Go HIGHER!"


